const MATCHERS = CATEGORY_TABLE.map(
  ([category, nouns]) =>
    [
      category,
      nouns.map(
        (noun) => new RegExp(`\\b${noun.replace(/[-/\\^$*+?.()|[\]{}]/g, '\\$&')}(s|es)?\\b`, 'i'),
      ),
    ] as const,
);

/** The category of the first table row with a noun in `text`, or null when none matches. */
export function categorize(text: string): string | null {
  for (const [category, patterns] of MATCHERS) {
    if (patterns.some((p) => p.test(text))) return category;
  }
  return null;
}

export const UNMAPPED_CATEGORY = 'other';
