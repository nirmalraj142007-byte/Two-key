/**
 * Writes the gateway's OpenAPI document to docs/openapi.json and the endpoint list by audience
 * to docs/API.md, both from apps/gateway/src/openapi.ts.
 *
 *   npm run openapi:export             write both
 *   npm run openapi:export -- --check  exit 1 if either is out of date
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { AUDIENCES, buildOpenApiDocument, ROUTES } from '@twokey/gateway';

const AUTH: Record<string, string> = {
  agentToken: '`Authorization: Bearer tk_agent_…` (one session)',
  humanAssertion: '`Authorization: Bearer <assertion>` (Ed25519 JWT from web, 60 s, single use)',
  paypalSignature: 'PayPal transmission headers, verified with PayPal',
  attemptToken: '`?t=` attempt token',
  metricsToken: '`Authorization: Bearer METRICS_TOKEN`',
  evalToken: '`x-eval-token: EVAL_ADMIN_TOKEN`',
};

function apiMarkdown(): string {
  const out = [
    '# Gateway API',
    '',
    'Generated by `npm run openapi:export` from `apps/gateway/src/openapi.ts`; do not edit by hand.',
    'The full schema is [openapi.json](openapi.json). Outside production the gateway serves it at',
    '`/docs/json` with Swagger UI at `/docs` (local: http://localhost:4000/docs).',
    '',
    'Every error body is `{ "error": { "code", "message", "requestId" } }`. A blocked purchase is a',
    'decision, not an error: HTTP 200 with `decision: "blocked"`. Another user\'s resource returns 404.',
  ];
  for (const [audience, description] of Object.entries(AUDIENCES)) {
    out.push('', `## ${audience}`, '', description, '', '| Method | Path | Auth | What it does |');
    out.push('| --- | --- | --- | --- |');
    for (const r of ROUTES.filter((x) => x.audience === audience)) {
      const scheme = r.security ?? (audience === 'public' ? undefined : 'humanAssertion');
      let auth = scheme ? (AUTH[scheme] ?? scheme) : 'none';
      if (r.scope) auth = `assertion, scope \`${r.scope}\``;
      else if (scheme === 'humanAssertion') auth = 'assertion, any scope';
      out.push(`| ${r.method.toUpperCase()} | \`${r.path}\` | ${auth} | ${r.summary} |`);
    }
  }
  out.push(
    '',
    '## Auth',
    '',
    ...Object.entries(AUTH).map(([k, v]) => `- **${k}**: ${v}.`),
    '',
    'Tokens starting with `tk_agent_` are always rejected on `/human/*`.',
    '',
  );
  return out.join('\n');
}

const files = [
  {
    path: new URL('../docs/openapi.json', import.meta.url),
    name: 'docs/openapi.json',
    text: `${JSON.stringify(buildOpenApiDocument(), null, 2)}\n`,
  },
  { path: new URL('../docs/API.md', import.meta.url), name: 'docs/API.md', text: apiMarkdown() },
];

if (process.argv.includes('--check')) {
  const stale = files.filter((f) => {
    try {
      return readFileSync(f.path, 'utf8') !== f.text;
    } catch {
      return true;
    }
  });
  for (const f of stale) console.error(`${f.name} is out of date: run npm run openapi:export`);
  if (stale.length > 0) process.exit(1);
  console.log('docs/openapi.json and docs/API.md are up to date');
} else {
  for (const f of files) {
    writeFileSync(f.path, f.text);
    console.log(`wrote ${f.name}`);
  }
}
